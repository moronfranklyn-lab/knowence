qas = [(q[0], q[0]) for q in QA]          # aid 与 qid 一一对应


def write_table(path, data, names, types):
    arrays = [pa.array([row[i] for row in data], type=t) for i, t in enumerate(types)]
    tbl = pa.Table.from_arrays(arrays, names=names)
    pq.write_table(tbl, path)
    print(f"  {os.path.basename(path):18s} {tbl.num_rows:3d} 行")


